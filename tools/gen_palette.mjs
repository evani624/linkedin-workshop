import fs from 'node:fs';
import { hex2rgb, rgb2oklch, oklch2hex, contrast } from './colors.mjs';
const TEAL = '#0C3B40', CHARCOAL = '#222B25', PAPER = '#F3F5F4';
const h0 = rgb2oklch(hex2rgb(TEAL))[2];
const names = ['الافتتاح', 'حدد اتجاهك', 'واجهتك', 'كيف تكتب منشور يوصل', 'الخوارزمية والوصول', 'تشريح منشورات حقيقية', 'وش تنشر ووش تخلي', 'التطبيق', 'الختام والتحدي'];
const first = [1, 4, 9, 11, 17, 22, 26, 27, 30];
const parts = names.map((name, k) => {
  const hue = (h0 + 40 * k) % 360;
  const tint = oklch2hex([0.84, 0.115, hue]).hex;   // on teal / charcoal
  const deep = oklch2hex([0.5, 0.125, hue]).hex;    // on paper / white
  return { n: k + 1, name, bearing: 40 * k, hue: Math.round(hue), tint, deep, from: first[k], to: (first[k + 1] ?? 32) - 1 };
});
for (const p of parts) console.log(p.n, p.name.padEnd(22), String(p.bearing).padStart(3) + '°', p.tint, contrast(p.tint, TEAL).toFixed(1), contrast(p.tint, CHARCOAL).toFixed(1), '|', p.deep, contrast(p.deep, PAPER).toFixed(1), contrast(p.deep, '#FFFFFF').toFixed(1));
const out = `// Generated by tools/gen_palette.mjs. Rakaya's two official colours, measured from the official mark,
// plus one accent per part. The accent's hue angle equals the part's compass bearing:
// part 1 sits at north and takes Rakaya teal's own hue (205deg), then every 40deg clockwise.
export const TEAL = '${TEAL}';
export const CHARCOAL = '${CHARCOAL}';
export const PAPER = '${PAPER}';
export const PARTS = ${JSON.stringify(parts, null, 2)};
export const partOfSlide = n => PARTS.find(p => n >= p.from && n <= p.to);
`;
fs.writeFileSync(new URL('../src/brand/palette.js', import.meta.url), out);
