// Builds dist/fonts.css: every face the deck uses, inlined as data: URIs so the page
// needs no network for type (the room's Wi-Fi may not be there on the day).
// Source: Fontsource packages of the Google Fonts families, all under the SIL Open Font License.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const nm = path.join(root, 'node_modules');

// family -> package, css files to read, weights to keep (null = variable, keep the range)
const FACES = [
  { family: 'Readex Pro', pkg: '@fontsource-variable/readex-pro', css: ['index.css'], subsets: ['arabic', 'latin'] },
  { family: 'IBM Plex Sans Arabic', pkg: '@fontsource/ibm-plex-sans-arabic', css: ['400.css', '500.css', '600.css', '700.css'], subsets: ['arabic', 'latin'] },
  { family: 'IBM Plex Mono', pkg: '@fontsource/ibm-plex-mono', css: ['400.css', '500.css'], subsets: ['latin'] }
];

let out = '/* Generated by tools/gen_fonts.mjs. Fonts: SIL Open Font License 1.1. */\n';
let total = 0;
for (const face of FACES) {
  for (const cssName of face.css) {
    const css = fs.readFileSync(path.join(nm, face.pkg, cssName), 'utf8');
    const blocks = css.split('@font-face').slice(1);
    for (const block of blocks) {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
      if (!file) continue;
      const subset = face.subsets.find(s => new RegExp(`-${s}-(wght|\\d+)-normal\\.woff2$`).test(file));
      if (!subset) continue;
      if (/italic/.test(file)) continue;
      const weight = /font-weight:\s*([^;]+);/.exec(block)[1].trim();
      const range = /unicode-range:\s*([^;]+);/.exec(block)[1].trim();
      const bytes = fs.readFileSync(path.join(nm, face.pkg, 'files', file));
      total += bytes.length;
      const variable = /wght/.test(file);
      out += `@font-face{font-family:'${face.family}';font-style:normal;font-display:block;font-weight:${weight};` +
        `src:url(data:font/woff2;base64,${bytes.toString('base64')}) format('${variable ? 'woff2-variations' : 'woff2'}');unicode-range:${range}}\n`;
    }
  }
}
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'fonts.css'), out);
console.log('fonts.css', (out.length / 1024).toFixed(0) + ' KB', 'from', (total / 1024).toFixed(0) + ' KB of woff2');
