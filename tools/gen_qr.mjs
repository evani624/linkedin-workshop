// Writes src/deck/qr.js: the QR matrix for each link the deck shows, as rows of 0/1.
import qrcode from 'qrcode-generator';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const LINKS = {
  linkedin: 'https://www.linkedin.com/in/muhmmadalsharif'
};

let out = '// Generated by tools/gen_qr.mjs (qrcode-generator, error correction M).\n';
for (const [name, url] of Object.entries(LINKS)) {
  const qr = qrcode(0, 'M');
  qr.addData(url);
  qr.make();
  const n = qr.getModuleCount();
  const rows = [];
  for (let r = 0; r < n; r++) {
    let row = '';
    for (let c = 0; c < n; c++) row += qr.isDark(r, c) ? '1' : '0';
    rows.push(row);
  }
  out += `export const QR_${name.toUpperCase()} = ${JSON.stringify({ url, rows })};\n`;
  console.log(name, n + 'x' + n, url);
}
fs.writeFileSync(path.join(root, 'src', 'deck', 'qr.js'), out);
